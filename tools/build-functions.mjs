// Regenerates functions/_lib/{engine,brief,master}.js from the files the browser uses,
// so the API builds exactly the plan the visitor saw. Run after changing the engine, the brief or the master data:
//   npm run build:functions
import { readFileSync, writeFileSync } from 'node:fs';
const root = new URL('..', import.meta.url);
const read = p => readFileSync(new URL(p, root), 'utf8');
const html = read('index.html');
const m = /<script type="application\/json" id="bp-master">([\s\S]*?)<\/script>/.exec(html);
if (!m) throw new Error('bp-master data not found in index.html');
JSON.parse(m[1]);
const head = src => '/* Generated by tools/build-functions.mjs from ' + src + '. Do not edit. */\n';
writeFileSync(new URL('functions/_lib/engine.js', root), head('assets/js/blueprint-engine.js') + read('assets/js/blueprint-engine.js') + '\nexport default BYEngine;\n');
writeFileSync(new URL('functions/_lib/brief.js', root), head('assets/js/blueprint-brief.js') + read('assets/js/blueprint-brief.js') + '\nexport default BYBrief;\n');
writeFileSync(new URL('functions/_lib/master.js', root), head('index.html #bp-master') + 'export default ' + m[1].trim() + ';\n');
console.log('functions/_lib updated');
