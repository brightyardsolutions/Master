// Regenerates functions/_lib/{engine,brief,master}.js from the modules the browser uses (src/lib/blueprint),
// so the API builds exactly the plan the visitor saw. Run by `npm run build`; on its own: npm run build:functions
import { readFileSync, writeFileSync } from 'node:fs';
const root = new URL('..', import.meta.url);
const read = p => readFileSync(new URL(p, root), 'utf8');
const master = JSON.stringify(JSON.parse(read('src/data/master.json')));
const head = src => '/* Generated by tools/build-functions.mjs from ' + src + '. Do not edit. */\n';
writeFileSync(new URL('functions/_lib/engine.js', root), head('src/lib/blueprint/engine.js') + read('src/lib/blueprint/engine.js'));
writeFileSync(new URL('functions/_lib/brief.js', root), head('src/lib/blueprint/brief.js') + read('src/lib/blueprint/brief.js'));
writeFileSync(new URL('functions/_lib/master.js', root), head('src/data/master.json') + 'export default ' + master + ';\n');
console.log('functions/_lib updated');
